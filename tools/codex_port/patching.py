"""Patch application and capture for the Codex skill port.

Version 0.1.0, owner Rock Lambros.

A patch is a unified diff against the mechanical output for one skill,
with ``a/`` and ``b/`` prefixes relative to the skill directory. It
carries the prose edits no generator can make. ``git apply`` does the
work because it is strict about context and refuses hunks that would
reach outside the directory it runs in.
"""
from __future__ import annotations

import shutil
import subprocess
import tempfile
from dataclasses import dataclass
from pathlib import Path

from tools.codex_port.sources import is_ignored

# Generated by the build from the manifest, so a difference here is never
# a hand adaptation worth capturing.
GENERATED_FILES = (Path("agents") / "openai.yaml",)


class PatchError(Exception):
    """git itself failed, as opposed to a patch that does not apply."""


@dataclass(frozen=True)
class PatchResult:
    ok: bool
    output: str


def find_patch(name: str, data_dirs: tuple[Path, ...]) -> Path | None:
    for data_dir in data_dirs:
        candidate = data_dir / "patches" / f"{name}.patch"
        if candidate.is_file():
            return candidate
    return None


def _git_apply(tree: Path, patch: Path, check_only: bool) -> PatchResult:
    command = ["git", "apply"]
    if check_only:
        command.append("--check")
    command.append(str(patch))
    result = subprocess.run(command, cwd=tree, capture_output=True, text=True, check=False)
    return PatchResult(ok=result.returncode == 0, output=(result.stdout + result.stderr).strip())


def check_patch(tree: Path, patch: Path) -> PatchResult:
    return _git_apply(tree, patch, check_only=True)


def apply_patch(tree: Path, patch: Path) -> PatchResult:
    return _git_apply(tree, patch, check_only=False)


def _copy_for_capture(src: Path, dst: Path, exclude: tuple[Path, ...]) -> None:
    shutil.copytree(src, dst, symlinks=False, ignore=lambda _d, names: {n for n in names if is_ignored(n)})
    for rel in exclude:
        target = dst / rel
        if target.exists():
            target.unlink()


HEADER_PREFIXES = ("diff --git ", "--- ", "+++ ")
# For an added or deleted file git names the surviving side on both
# headers (``a/t/x b/t/x``), so all four forms have to go.
CAPTURE_PREFIXES = ((" a/s/", " a/"), (" a/t/", " a/"), (" b/s/", " b/"), (" b/t/", " b/"))


def _strip_capture_prefixes(diff_text: str) -> str:
    lines = []
    for line in diff_text.splitlines():
        if line.startswith(HEADER_PREFIXES):
            for old, new in CAPTURE_PREFIXES:
                line = line.replace(old, new)
        lines.append(line)
    return "\n".join(lines) + "\n"


def capture_patch(generated: Path, installed: Path, out: Path, exclude: tuple[Path, ...] = GENERATED_FILES) -> int:
    """Write a patch turning ``generated`` into ``installed``.

    Returns the number of files that differ. Writes nothing when that is
    zero, so an unchanged skill never gets an empty patch file. ``exclude``
    defaults to the generated files, which a captured hand patch must not
    carry. A caller that wants the whole picture, such as ``diff``, passes
    an empty tuple.
    """
    with tempfile.TemporaryDirectory() as tmp:
        parent = Path(tmp)
        _copy_for_capture(generated, parent / "s", exclude)
        _copy_for_capture(installed, parent / "t", exclude)
        result = subprocess.run(
            ["git", "diff", "--no-index", "--no-color", "--no-renames", "s", "t"],
            cwd=parent,
            capture_output=True,
            text=True,
            check=False,
        )
    # git diff exits 0 for no differences, 1 for differences, anything else is an error.
    if result.returncode == 0:
        return 0
    if result.returncode != 1:
        raise PatchError(result.stderr.strip() or f"git diff exited {result.returncode}")
    text = _strip_capture_prefixes(result.stdout)
    changed = sum(1 for line in text.splitlines() if line.startswith("diff --git "))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    return changed
